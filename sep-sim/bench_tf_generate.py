def resume_rows(path):
    """The resumable raw file, tolerant of a truncated LAST line (an interrupted write): that line is dropped with a
    warning and the file rewritten without it (the conversation is regenerated); a bad line elsewhere stops."""
    if not os.path.exists(path):
        return []
    lines = open(path, encoding="utf-8").read().split("\n")
    while lines and not lines[-1].strip():
        lines.pop()
    out = []
    for i, l in enumerate(lines):
        if not l.strip():
            continue
        try:
            out.append(json.loads(l))
        except ValueError:
            if i != len(lines) - 1:
                raise SystemExit("%s: line %d is not JSON (not the last line): refusing to resume" % (path, i + 1))
            print("WARNING: %s: dropping a truncated last line (%d chars); that conversation is regenerated"
                  % (path, len(l)), flush=True)
            write_atomic(path, "".join(json.dumps(d, ensure_ascii=False) + "\n" for d in out))
    return out


def validate_rows(rows, expected_turns, max_samples=3):
    """The generations file the scorer will read: refused (ValueError) unless every expected (record_id, turn) has
    exactly one row with the schema, the END invariants and no retired flag. expected_turns: record_id -> n."""
    seen = {}
    for i, r in enumerate(rows):
        miss = [k for k in REQUIRED_KEYS if k not in r]
        if miss:
            raise ValueError("row %d: missing %s" % (i, miss))
        old = [k for k in RETIRED_KEYS if k in r]
        if old:
            raise ValueError("row %d: retired flag(s) %s (renamed 2026-09-29)" % (i, old))
        rid, t = r["record_id"], r["turn_index"]
        if not isinstance(rid, str) or not isinstance(t, int) or isinstance(t, bool) or t < 1:
            raise ValueError("row %d: bad record_id / turn_index %r %r" % (i, rid, t))
        if r["is_first_turn"] is not (t == 1):
            raise ValueError("row %d: is_first_turn %r at turn %d" % (i, r["is_first_turn"], t))
        if not isinstance(r["greedy"], str) or not isinstance(r["greedy_end_decision"], bool):
            raise ValueError("row %d: greedy must be str, greedy_end_decision bool" % i)
        if r["greedy_end_decision"] != (not r["greedy"].strip()):
            raise ValueError("row %d (%s t%d): END flag %r with greedy %r" % (i, rid, t, r["greedy_end_decision"],
                                                                              r["greedy"][:40]))
        s, f = r["samples"], r["sample_end_decisions"]
        if not (isinstance(s, list) and all(isinstance(x, str) for x in s)):
            raise ValueError("row %d: samples must be a list of str" % i)
        if not (isinstance(f, list) and all(isinstance(x, bool) for x in f)) or len(f) != len(s):
            raise ValueError("row %d: sample_end_decisions must be bools, one per sample" % i)
        if "sample_guard_reasons" in r and len(r["sample_guard_reasons"]) != len(s):
            raise ValueError("row %d: sample_guard_reasons not aligned with samples" % i)
        if max_samples > 0 and len(s) != max_samples:
            raise ValueError("row %d: %d samples, expected %d" % (i, len(s), max_samples))
        if any(not x.strip() and not y for x, y in zip(s, f)):
            raise ValueError("row %d: an empty sample without its END flag" % i)
        if REDACTION in r["greedy"] or any(REDACTION in x for x in s):
            raise ValueError("row %d: redaction marker in the text" % i)
        if (rid, t) in seen:
            raise ValueError("duplicate row %s t%d" % (rid, t))
        seen[(rid, t)] = i
    want = {(rid, t) for rid, n in expected_turns.items() for t in range(1, n + 1)}
    if set(seen) != want:
        raise ValueError("rows do not cover the gold user turns exactly: missing %s, extra %s"
                         % (sorted(want - set(seen))[:5], sorted(set(seen) - want)[:5]))
    return {"n_rows": len(rows), "n_records": len(expected_turns),
            "n_end_rows": sum(1 for r in rows if r["greedy_end_decision"]),
            "n_end_rows_planner": sum(1 for r in rows if r.get("end_source") == "planner_end_previous_turn"),
            "n_end_rows_speaker_blank": sum(1 for r in rows if r.get("end_source") == "speaker_blank")}


