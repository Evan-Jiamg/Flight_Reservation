class DryEnv:
    """Pure-python stand-in for Task2Env (dry run / tests): task1_generate rows with the real field names, seeded
    Planner ends and an occasional blank Ditto pick; no model."""

    def __init__(self, corpus, adapter_name):
        self.recs = {}
        with open(corpus, encoding="utf-8") as f:
            for l in f:
                if l.strip():
                    r = json.loads(l)
                    self.recs[r["conversation_id"]] = r
        self.adapter_name = adapter_name
        self.seen_annotations = 0
        self.fewshot = None

    def describe(self):
        return {"arm": "pend", "dry_run": True, "planner_backend": "dry", "selector": "borda", "implicit_profile": True}

    def task1_generate(self, conversation_id, seed=0, keep_prompts=False):
        rec = self.recs[conversation_id]
        users = user_turns(rec)
        for m in rec["chat_messages"]:
            if str(m.get("participant_name", "")).lower() != "user" and m.get("annotations"):
                self.seen_annotations += 1           # must stay 0: the exporter strips them first
        rng = random.Random("%s|%d" % (conversation_id, seed))
        rows, prev = [], False
        for t in range(1, len(users) + 1):
            ncand = 4 + (1 if rng.random() < 0.2 else 0)
            cands = ["c%d t%d %s" % (j, t, conversation_id[:4]) for j in range(ncand)]
            if rng.random() < 0.1:
                cands = [""] * ncand                       # Ditto produced only blanks
            idx = rng.randrange(ncand)
            reasons = [("near_copy" if rng.random() < 0.25 else "") for _ in range(ncand)]
            reasons[idx] = ""
            end_t = t >= 2 and rng.random() < 0.3
            rows.append({"record_id": rec["record_id"], "conversation_id": conversation_id, "turn_index": t,
                         "greedy": cands[idx], "greedy_ended": (not cands[idx]) or prev,
                         "ended_by_prev_decision": prev, "speaker_ended": not cands[idx],
                         "planner_ends_session": end_t,
                         "samples": [c for j, c in enumerate(cands) if j != idx],
                         "samples_ended": [not c for j, c in enumerate(cands) if j != idx],
                         "samples_speaker_ended": [not c for j, c in enumerate(cands) if j != idx],
                         "selected_index": idx, "guard_reasons": reasons, "profile": "- act: dry", "guard_no_survivor": False,
                         "planner_unparsed": False, "planner_hit_max_new": False, "emitted_capped": False,
                         "planner_fit": {"gen_adapter": self.adapter_name}})
            prev = end_t
        k1 = {"record_id": rec["record_id"], "conversation_id": conversation_id, "turn_index": len(users) + 1,
              "ended": prev, "ended_by_decision_at_n": prev, "ended_speaker": False,
              "planner_fit": {"gen_adapter": self.adapter_name}}
        return rows, k1


