def to_benchmark_rows(raw_rows, rec, intent_variant, max_samples=3):
    """task1_generate rows of ONE conversation -> benchmark generation rows (one per gold user turn)."""
    goal = (rec.get("scenario") or {}).get("goal") or {}
    out = []
    for r in sorted(raw_rows, key=lambda x: int(x["turn_index"])):
        t = int(r["turn_index"])
        prev = bool(r.get("ended_by_prev_decision"))
        text = r.get("greedy") or ""
        blank = bool(r.get("speaker_ended")) or not text.strip()
        end = prev or blank
        cands = list(r.get("samples") or [])
        flags = [bool(x) for x in (r.get("samples_speaker_ended") or r.get("samples_ended") or [False] * len(cands))]
        if len(flags) != len(cands):
            raise ValueError("%s t%d: %d samples, %d sample flags" % (rec["record_id"], t, len(cands), len(flags)))
        flags = [f or not (c or "").strip() for c, f in zip(cands, flags)]
        k = max_samples if max_samples > 0 else len(cands)
        if len(cands) < k:
            raise ValueError("%s t%d: %d non-selected candidates < %d samples" % (rec["record_id"], t, len(cands), k))
        # guard reasons of the candidates (task2_env: aligned with ALL candidates, the selected one included);
        # the samples are the candidates without the selected index, in order -> the same order here
        reasons = r.get("guard_reasons")
        idx = r.get("selected_index")
        if isinstance(reasons, list) and isinstance(idx, int) and len(reasons) == len(cands) + 1:
            s_reasons = [x or None for i, x in enumerate(reasons) if i != idx]
        else:
            s_reasons = ["unknown"] * len(cands)
        if end and prev:
            samples, s_flags, source = [""] * k, [True] * k, "planner_end_previous_turn"
            g_reasons = ["end_row"] * k
        else:
            samples, s_flags = cands[:k], flags[:k]
            g_reasons = s_reasons[:k]
            source = "speaker_blank" if end else None
        out.append({
            "record_id": rec["record_id"], "turn_index": t, "is_first_turn": t == 1,
            "discipline": goal.get("discipline", "unspecified"), "stage": goal.get("stage", "unspecified"),
            "intent_variant": intent_variant,
            "greedy": "" if end else text, "greedy_end_decision": bool(end),
            "samples": samples, "sample_end_decisions": s_flags,
            "sample_guard_reasons": g_reasons,       # None = passed the guards; else why it was rejected
            # diagnostics (not read by the scorer)
            "end_mapping": "M2", "end_source": source,
            "planner_ends_session": bool(r.get("planner_ends_session")),   # decided at t -> END at row t+1
            "n_candidates": len(cands) + 1, "selected_index": r.get("selected_index"),
            "selected_guard_reason": (reasons[idx] or None) if (isinstance(reasons, list) and isinstance(idx, int)
                                                                and 0 <= idx < len(reasons)) else None,
            "guard_no_survivor": r.get("guard_no_survivor"), "planner_unparsed": r.get("planner_unparsed"),
            "planner_hit_max_new": r.get("planner_hit_max_new"), "emitted_capped": r.get("emitted_capped"),
            "profile": r.get("profile")})
    return out


def sample_guard_stats(rows):
    """S1 (audit 2026-10-01): how many of the sample slots the scorer reads hold guard-REJECTED candidates (the 2AFC
    reads the first non-empty sample, the act labels every sample, utterance_validity any-sample rule hits)."""
    from collections import Counter
    live = [r for r in rows if r.get("end_source") != "planner_end_previous_turn"]
    slots = [(x, s) for r in live for x, s in zip(r.get("sample_guard_reasons") or [], r["samples"])]
    rej = [x for x, _ in slots if x]
    first = []
    for r in live:
        j = next((i for i, s in enumerate(r["samples"]) if s.strip()), None)
        if j is not None:
            first.append((r.get("sample_guard_reasons") or [None] * (j + 1))[j])
    return {"n_rows_with_produced_samples": len(live), "n_sample_slots": len(slots),
            "n_sample_slots_guard_rejected": len(rej),
            "sample_slot_guard_rejected_rate": round(len(rej) / len(slots), 4) if slots else None,
            "guard_reasons": dict(Counter(rej)),
            "n_rows_first_nonempty_sample_guard_rejected": sum(1 for x in first if x),
            "first_nonempty_sample_guard_rejected_rate": round(sum(1 for x in first if x) / len(first), 4) if first else None,
            "n_selected_guard_rejected": sum(1 for r in live if r.get("selected_guard_reason")),
            "note": "samples = the selector's non-selected candidates (sep1st convention), so guard-rejected text "
                    "reaches the 2AFC (first non-empty sample), the act annotation (every sample) and the any-sample "
                    "validity rate"}


def length_stats(rows, speaker_tok=None):
    """S2: the emitted greedy texts against the protocol's 200-token utterance cap."""
    texts = [r["greedy"] for r in rows if r["greedy"].strip()]
    ws = [len(t.split()) for t in texts]
    out = {"n_nonempty_greedy": len(texts), "n_greedy_over_200_whitespace_tokens": sum(1 for n in ws if n > 200),
           "max_greedy_whitespace_tokens": max(ws) if ws else 0}
    out["share_greedy_over_200_whitespace_tokens"] = round(out["n_greedy_over_200_whitespace_tokens"] / len(ws), 4) if ws else None
    if speaker_tok is not None:
        try:
            dt = [len(speaker_tok(t, add_special_tokens=False)["input_ids"]) for t in texts]
            out.update({"n_greedy_over_200_ditto_tokens": sum(1 for n in dt if n > 200),
                        "share_greedy_over_200_ditto_tokens": round(sum(1 for n in dt if n > 200) / len(dt), 4) if dt else None,
                        "max_greedy_ditto_tokens": max(dt) if dt else 0})
        except Exception as e:                      # a diagnostic: recorded, not fatal
            out["ditto_tokens"] = "not available: %r" % (e,)
    else:
        out["ditto_tokens"] = "not available (no Ditto tokenizer in this env)"
    return out


