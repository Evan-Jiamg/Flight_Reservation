def compare_with_test(raw_by_cid, test_rows, policy_sha):
    """Our Planner / Ditto decisions vs the test evaluation's Task 1 run of the SAME policy (RUN/test.jsonl kind task1):
    same code, seed 0, Planner greedy on vLLM -- equal unless the server's greedy decoding is not bit-reproducible."""
    ref = {r["conversation_id"]: r["task1"] for r in test_rows
           if r.get("kind") == "task1" and r.get("policy_sha") == policy_sha}
    if not ref:
        return {"available": False}
    n = agree = 0
    diffs = []
    for cid, d in raw_by_cid.items():
        t1 = ref.get(cid)
        if t1 is None:
            continue
        mine = {int(r["turn_index"]): (bool(r["planner_ends_session"]), bool(r["speaker_ended"])) for r in d["rows"]}
        for x in t1["turns"]:
            n += 1
            theirs = (bool(x["ended_planner"]), bool(x["speaker_blank"]))
            if mine.get(int(x["t"])) == theirs:
                agree += 1
            else:
                diffs.append([cid, x["t"], list(theirs), list(mine.get(int(x["t"]), (None, None)))])
        n += 1
        if bool(d["k1"]["ended"]) == bool(t1["k1_ended"]):
            agree += 1
        else:
            diffs.append([cid, "k1", t1["k1_ended"], d["k1"]["ended"]])
    return {"available": True, "n_decisions": n, "n_agree": agree, "diffs": diffs[:40]}


def compare_with_k1(raw_by_cid, k1_rows, recs):
    """Our K+1 END vs the K+1 probe file the --termination JSON was reduced from."""
    rid2cid = {rec["record_id"]: cid for cid, rec in recs.items()}
    ref = {rid2cid.get(r["record_id"]): bool(r["ended"]) for r in k1_rows}
    if not ref:
        return {"available": False}
    diffs = [[cid, ref[cid], bool(d["k1"]["ended"])] for cid, d in raw_by_cid.items()
             if cid in ref and ref[cid] != bool(d["k1"]["ended"])]
    return {"available": True, "n": sum(1 for c in raw_by_cid if c in ref), "n_disagree": len(diffs), "diffs": diffs}


