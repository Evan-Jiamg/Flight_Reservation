def parse(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--final", action="store_true", help="required: this reads the test split")
    ap.add_argument("--run-dir", required=True, help="runs/pend_f<F>_v17")
    ap.add_argument("--update", type=int, required=True, help="0 (SFT u0) or the final update (final.json)")
    ap.add_argument("--fold", type=int, required=True)
    ap.add_argument("--splits", default="/tmp2/mzjiang_usersim/grpo_planner/splits_v1.json")
    ap.add_argument("--bench", default=BENCH, help="the benchmark repo (read only)")
    ap.add_argument("--corpus", default=DEFAULT_CORPUS)
    ap.add_argument("--planner-path", default=None)
    ap.add_argument("--planner-backend", choices=("vllm",), default="vllm")
    ap.add_argument("--vllm-url", default="http://127.0.0.1:8031/v1")
    ap.add_argument("--gpu", type=int, default=0, help="Ditto-8B's GPU")
    ap.add_argument("--implicit-profile", type=int, choices=(0, 1), default=1)
    ap.add_argument("--selector", choices=("length", "borda"), default="borda")
    ap.add_argument("--batch", type=int, choices=(0, 1), default=1)
    ap.add_argument("--max-batch", type=int, default=8)
    ap.add_argument("--workers", type=int, default=4, help="conversations in parallel (the test evaluation used 4)")
    ap.add_argument("--max-samples", type=int, default=3, help="samples per row (protocol: 3); 0 = every other candidate")
    ap.add_argument("--intent-variant", default=None, help="default pend_v17_f<F>_u<k>")
    ap.add_argument("--test-jsonl", default=None, help="default RUN/test.jsonl (decision cross-check)")
    ap.add_argument("--k1-probe", default=None, help="the K+1 probe file of this policy (cross-check), e.g. k1_u0.jsonl")
    ap.add_argument("--force-unload", action="store_true",
                    help="unload other adapters on the Planner vLLM server (default: refuse to start)")
    ap.add_argument("--out", required=True)
    ap.add_argument("--dry-run", action="store_true", help="fake env: no GPU, no model (tests)")
