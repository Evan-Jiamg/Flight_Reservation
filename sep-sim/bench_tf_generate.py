def foreign_adapters(remote, ours):
    """Adapters loaded on the Planner vLLM server other than the base and ours (use_adapter would unload them)."""
    import vllm_planner
    served = [m.get("id") for m in vllm_planner._get(remote.url + "/models").get("data", [])]
    return [n for n in served if n not in (remote.base_name, ours)]


def build_env(a, gates):
    """Task2Env exactly as train_planner_rl.Trainer.build / eval_test_rl (pend, Implicit Profile, Borda, few-shot =
    splits[fold].train_all, Ditto on --gpu, batching), generation-only: the Planner's tokenizer here, generation on the
    vLLM server with the checkpoint's adapter (name p<k>-<sha12>, as Trainer.sync_generation_policy), no R0 / judge."""
    if a.dry_run:
        return DryEnv(a.corpus, "p%d-%s" % (a.update, gates["adapter_dir_sha256"][:12]))
    import torch
    torch.cuda.set_device(int(a.gpu))
    from task2_env import Task2Env, PlannerLM, setup_environment, make_fewshot_pool
    import task1_v4
    setup_environment("pend")
    planner = task1_v4.make_planner(PlannerLM, a.planner_path, a.gpu, None, "vllm", a.vllm_url)
    ours = "p%d-%s" % (a.update, gates["adapter_dir_sha256"][:12])
    foreign = foreign_adapters(planner.remote, ours)
    if foreign and not a.force_unload:
        raise SystemExit("the Planner vLLM server %s holds other adapter(s) %s (another job may be using them); loading "
                         "ours would unload them. Pass --force-unload only if they are not in use." % (a.vllm_url, foreign))
    planner.remote.use_adapter(gates["adapter_dir"], "p%d" % a.update)
    planner.adapter = gates["adapter_dir"]
    env = Task2Env("pend", a.gpu, planner, judge=None, corpus=a.corpus, batch=bool(a.batch), max_batch=a.max_batch,
                   implicit_profile=bool(a.implicit_profile), selector=a.selector, task1_only=True)
    env.fewshot = make_fewshot_pool(env.recs, gates["fewshot_pool_ids"])
    return env


