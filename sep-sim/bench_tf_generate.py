def load_gates(a):
    """Every refusal before any generation: finished run, the update evaluated by the spec, adapter + manifest
    (fold, splits sha, no test id in any training list, the run's settings), the test ids = the benchmark fold's
    session ids, pinned manifest / corpus shas. -> dict of facts for the provenance."""
    run = a.run_dir
    fin_p = os.path.join(run, "final.json")
    if not os.path.exists(fin_p):
        raise SystemExit("%s has no final.json: the run is not finished" % run)
    fin = json.load(open(fin_p, encoding="utf-8"))
    if not fin.get("validated") or fin.get("final_update") is None:
        raise SystemExit("final.json has no validated final update: %r" % fin)
    if a.update not in (0, int(fin["final_update"])):
        raise SystemExit("--update %d: only u0 (SFT) and the final u%d were evaluated on the test split (spec v17 §5)"
                         % (a.update, fin["final_update"]))
    ck = os.path.join(run, "ckpt", "u%05d" % a.update)
    adapter = os.path.join(ck, "adapter")
    for p in (adapter, os.path.join(ck, "rl_manifest.json"), os.path.join(ck, "state.json")):
        if not os.path.exists(p):
            raise SystemExit("missing %s" % p)
    man = json.load(open(os.path.join(ck, "rl_manifest.json"), encoding="utf-8"))
    st = json.load(open(os.path.join(ck, "state.json"), encoding="utf-8"))
    if a.update == int(fin["final_update"]) and st.get("policy_sha") != fin.get("policy_sha"):
        raise SystemExit("ckpt u%d policy sha %s != final.json %s" % (a.update, str(st.get("policy_sha"))[:12],
                                                                       str(fin.get("policy_sha"))[:12]))
    if int(man.get("fold", -1)) != a.fold:
        raise SystemExit("LEAK GATE: adapter trained on fold %s, scored on fold %d" % (man.get("fold"), a.fold))
    if man.get("init_adapter"):
        raise SystemExit("adapter trained on top of init adapter %s" % man["init_adapter"])
    splits_sha = sha_file(a.splits)
    if man.get("splits_sha256") != splits_sha:
        raise SystemExit("LEAK GATE: adapter trained with another split file (sha %s, now %s)"
                         % (str(man.get("splits_sha256"))[:12], splits_sha[:12]))
    sp = [x for x in json.load(open(a.splits, encoding="utf-8"))["folds"] if int(x["fold"]) == a.fold][0]
    test_all = sorted(sp["test_all"])
    forb = set(sp["forbidden_for_training"])
    if not set(test_all) <= forb:
        raise SystemExit("splits fold %d: test_all not inside forbidden_for_training" % a.fold)
    for k in ("train_scenarios", "train_conversations", "fewshot_pool", "sft_conversations"):
        v = man.get(k)
        ids = v if isinstance(v, (list, tuple)) else (list(v) if isinstance(v, dict) else [])
        bad = set(map(str, ids)) & set(test_all)
        if bad:
            raise SystemExit("LEAK GATE: manifest %s contains test ids %s" % (k, sorted(bad)[:3]))
    if set(sp["train_all"]) & forb:
        raise SystemExit("few-shot pool (train_all) intersects forbidden_for_training")
    fp = man.get("fewshot_pool")
    fp_ids = set(map(str, fp if isinstance(fp, (list, tuple)) else (list(fp) if isinstance(fp, dict) else [])))
    if fp_ids != set(sp["train_all"]):
        raise SystemExit("the adapter's few-shot pool (rl_manifest fewshot_pool, %d ids) != splits[%d].train_all (%d ids): "
                         "only in manifest %s / only in splits %s" % (
                             len(fp_ids), a.fold, len(sp["train_all"]), sorted(fp_ids - set(sp["train_all"]))[:3],
                             sorted(set(sp["train_all"]) - fp_ids)[:3]))
    want = {"arm": "pend", "implicit_profile": a.implicit_profile, "selector": a.selector, "fewshot": "fold",
            "planner_backend": a.planner_backend}
    diff = {k: (man.get(k), v) for k, v in want.items() if man.get(k) != v}
    if a.planner_path and man.get("planner_path") and \
            os.path.normpath(str(man["planner_path"])) != os.path.normpath(a.planner_path):
        diff["planner_path"] = (man["planner_path"], a.planner_path)
    if diff:
        raise SystemExit("the adapter was trained with other settings than this generation: %r" % diff)
    bm_p = os.path.join(a.bench, BENCH_MANIFEST)
    bm_sha = sha_file(bm_p)
    if bm_sha != BENCH_MANIFEST_SHA256:
        raise SystemExit("benchmark fold manifest changed (sha %s, pinned %s)" % (bm_sha[:12], BENCH_MANIFEST_SHA256[:12]))
    bm = json.load(open(bm_p, encoding="utf-8"))
    bf = [x for x in bm["folds"] if int(x["fold"]) == a.fold][0]
    if sorted(bf["session_ids"]) != test_all:
        raise SystemExit("splits fold %d test_all != benchmark fold %d session_ids" % (a.fold, a.fold))
    c_sha = sha_file(a.corpus)
    if c_sha != CORPUS_SHA256 or c_sha != bm.get("source_sha256"):
        raise SystemExit("corpus sha %s is not the official corpus (pinned %s, manifest %s)"
                         % (c_sha[:12], CORPUS_SHA256[:12], str(bm.get("source_sha256"))[:12]))
    return {"final_json_sha256": sha_file(fin_p), "final_update": int(fin["final_update"]),
            "stop_reason": fin.get("stop_reason"), "adapter_dir": os.path.abspath(adapter),
            "adapter_dir_sha256": sha_dir(adapter),
            "adapter_files_sha256": {fn: sha_file(os.path.join(adapter, fn)) for fn in sorted(os.listdir(adapter))
                                     if os.path.isfile(os.path.join(adapter, fn))},
            "policy_sha": st.get("policy_sha"), "rl_manifest_sha256": sha_file(os.path.join(ck, "rl_manifest.json")),
            "state_json_sha256": sha_file(os.path.join(ck, "state.json")),
            "rl_manifest_settings": {k: man.get(k) for k in ("arm", "fold", "implicit_profile", "selector", "fewshot",
                                                            "planner_backend", "planner_path", "spec_version")},
            "splits_sha256": splits_sha, "test_all": test_all, "fewshot_pool_ids": sorted(sp["train_all"]),
            "bench_manifest_sha256": bm_sha, "bench_fold": {k: bf.get(k) for k in ("fold", "goals", "personas",
                                                                                    "n_sessions", "n_user_turns")},
            "corpus_sha256": c_sha}


def code_provenance():
    out = {f: sha_file(os.path.join(HERE, f)) for f in CODE_FILES if os.path.exists(os.path.join(HERE, f))}
    lst = os.path.join(HERE, "local_sha_v17.txt")         # the deployed snapshot's own sha list (code_snapshots/pend_v17)
    snap = None
    if os.path.exists(lst):
        bad = []
        for line in open(lst, encoding="utf-8"):
            parts = line.split()
            if len(parts) == 2:
                p = os.path.join(HERE, parts[1].lstrip("*"))
                if not os.path.exists(p) or sha_file(p) != parts[0]:
                    bad.append(parts[1])
        snap = {"list": lst, "list_sha256": sha_file(lst), "mismatches": bad}
    return out, snap


